"""Command line: ``python -m tex2typ chapter.tex --out generated``."""
from __future__ import annotations

import argparse
import json
import os
import re
import tomllib
from pathlib import Path

from .emit import Emitter
from .index import Index, plain_text
from .model import Heading, Inline, Math, Text
from .parser import parse_file

THEME = Path(__file__).resolve().parents[1] / "theme.typ"
HEADER = "// Generated by tex2typ from {source}. Do not edit; edit the .tex and regenerate.\n"


def part_id(part: int) -> str:
    return f"s{part:02d}"


def title_plain(inlines: list[Inline]) -> str:
    """A readable one-line title (math reduced to its letters), for file names and HTML titles."""
    pieces = []
    for node in inlines:
        if isinstance(node, Text):
            pieces.append(node.value)
        elif isinstance(node, Math):
            pieces.append(re.sub(r"\\[A-Za-z]+|[{}\\]", "", node.src))
    return re.sub(r"\s+", " ", "".join(pieces)).strip()


def load_overrides(path: Path | None) -> dict[str, str]:
    if path is None or not path.is_file():
        return {}
    return dict(tomllib.loads(path.read_text(encoding="utf-8")).get("tal-number", {}))


def theme_import(directory: Path, theme: Path) -> str:
    """The ``#import`` line for the theme, relative to the generated file's directory."""
    relative = os.path.relpath(theme, directory).replace(os.sep, "/")
    return f'#import "{relative}": *\n'


def convert(tex: Path, out: Path, overrides: Path | None = None, theme: Path = THEME) -> dict:
    """Write the Typst files for ``tex`` into ``out``; return the section table."""
    document = parse_file(tex)
    index = Index(document, load_overrides(overrides))
    header = HEADER.format(source=tex.name)
    (out / "body").mkdir(parents=True, exist_ok=True)

    parts: list[list] = [document.front] + document.sections
    sections = []
    chapter_title = title_plain(document.title)
    for part, blocks in enumerate(parts):
        emitter = Emitter(index, part)
        body = emitter.blocks(blocks)
        if part == 0:
            intro = f"#heading(numbering: none)[{emitter.inlines(document.title)}]\n\n"
            title = "Introduction and conventions"
            body = intro + body
        else:
            title = title_plain(blocks[0].title) if isinstance(blocks[0], Heading) else f"Section {part}"
        name = part_id(part)
        (out / "body" / f"{name}.typ").write_text(
            header + theme_import(out / "body", theme) + "\n" + body + "\n", encoding="utf-8")
        entry = (header + theme_import(out, theme) +
                 f'#show: book-section.with(part: {part}, title: {json.dumps(title)})\n'
                 f'#include "body/{name}.typ"\n')
        (out / f"{name}.typ").write_text(entry, encoding="utf-8")
        sections.append({"id": name, "part": part, "title": title})

    includes = "".join(f'#include "body/{s["id"]}.typ"\n' for s in sections)
    book = (header + theme_import(out, theme) +
            f'#show: book.with(title: [{Emitter(index, 0).inlines(document.title)}], '
            f'subtitle: [A Lean-checked blueprint, following Talagrand, _Spin Glasses: A Challenge for '
            f'Mathematicians_, Volume I])\n' + includes)
    (out / "book.typ").write_text(book, encoding="utf-8")

    names = sorted({n for blocks in parts for n in iter_lean_names(blocks)})
    write_json(out / "sections.json", {"title": chapter_title, "sections": sections})
    write_json(out / "lean-names.json", names)
    write_json(out / "labels.json", {k: vars(v) for k, v in index.labels.items()})
    return {"sections": sections, "lean_names": names, "labels": len(index.labels)}


def iter_lean_names(blocks):
    """All ``\\lean`` names below ``blocks`` (for the manifest checked against the Lean build)."""
    from .model import Environment, ListBlock, Proof
    for block in blocks:
        if isinstance(block, Environment):
            yield from block.lean
            yield from iter_lean_names(block.blocks)
        elif isinstance(block, Proof):
            yield from iter_lean_names(block.blocks)
        elif isinstance(block, ListBlock):
            for item in block.items:
                yield from iter_lean_names(item.blocks)


def write_json(path: Path, value) -> None:
    path.write_text(json.dumps(value, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("tex", type=Path)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--overrides", type=Path)
    args = parser.parse_args(argv)
    summary = convert(args.tex, args.out, args.overrides)
    print(f"Converted {args.tex.name}: {len(summary['sections'])} parts, "
          f"{summary['labels']} labels, {len(summary['lean_names'])} Lean names -> {args.out}")
    return 0
